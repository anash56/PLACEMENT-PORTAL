import express from "express";
import { createJob, getJobs, getJobById, updateJob, deleteJob } from "../controllers/jobController.js";
import protect from "../middleware/authMiddleware.js";
import { collegeAdminOnly, superAdminOnly } from "../middleware/adminMiddleware.js";
import { csrfProtect } from "../middleware/csrfMiddleware.js";
const router = express.Router();
router.post("/", protect, collegeAdminOnly, csrfProtect, createJob);
router.get("/", protect, getJobs);
router.get("/:id", protect, getJobById);
router.patch("/:id", protect, collegeAdminOnly, csrfProtect, updateJob);
router.delete("/:id", protect, collegeAdminOnly, csrfProtect, deleteJob);
export default router;
