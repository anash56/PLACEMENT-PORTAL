import express from "express";
import protect from "../middleware/authMiddleware.js";
import { collegeAdminOnly, superAdminOnly } from "../middleware/adminMiddleware.js";
import { csrfProtect } from "../middleware/csrfMiddleware.js";
import { applyJob, getMyApplications, getApplicantsByJob, updateApplicationStatus } from "../controllers/applicationController.js";
const router = express.Router();
router.post("/:jobId", protect, csrfProtect, applyJob);
router.get("/my", protect, getMyApplications);
router.get("/job/:jobId", protect, collegeAdminOnly, getApplicantsByJob);
router.patch("/:id", protect, collegeAdminOnly, csrfProtect, updateApplicationStatus);
export default router;
